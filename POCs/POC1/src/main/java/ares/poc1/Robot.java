package ares.poc1;

public class Robot {
    private String id;
    private double x;
    private double y;
    private double heading;
    private int energy;
    private int hp;

    public String getId() {
        return id;
    }

    public double getX() {
        return x;
    }

    public double getY() {
        return y;
    }

    public double getHeading() {
        return heading;
    }

    public int getEnergy() {
        return energy;
    }

    public int getHp() {
        return hp;
    }
}
